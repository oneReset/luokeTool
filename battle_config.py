# 相关全局参数（影响所有模式，含模式4）在 config.py 中：
#   - match_threshold      战斗开始/结束判定阈值（默认 0.40）
#   - poll_interval_sec    主循环轮询间隔（默认 0.4 秒）
#   - trigger_cooldown_sec 战斗内按键最小间隔（默认 1.0 秒，即攻击节奏）
