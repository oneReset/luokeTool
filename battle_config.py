# ── 战斗行为 ────────────────────────────────────────────────────────

# 攻击技能键：污染战斗中循环按此键把目标打到虚脱（游戏技能栏 "1"/"2"/"3"/"4"）
ATTACK_KEY = "1"

# 球槽键：点击捕捉按钮后出现选球界面，按此键选择球槽（可选 "1"~"6"）
BALL_SLOT_KEY = "3"

# 确认键：选球后按下确认开始捕捉（空格键）
CONFIRM_KEY = "space"

# 普通战斗（非污染）的行为：
#   "catch"  = 直接进入捕捉流程（目标一开始就处于可捕捉状态）
#   "escape" = 按 ESC 逃跑
NORMAL_BATTLE_ACTION = "catch"

# ── 时序参数（单位：秒）─────────────────────────────────────────────

# 降级模式的固定延时：点击捕捉按钮 → 按球槽键的等待。
# 主路径为模板闭环（面板出现即按键）；仅在模板缺失或连续失败降级时使用此值。
CATCH_CLICK_DELAY = 0.35

# 按球槽键 → 按确认键的等待
CATCH_CONFIRM_DELAY = 0.25

# 按确认键后的额外冷却：必须覆盖整个捕捉动画（球飞出→摇晃→成功/失败），
# 否则动画中途会误触发重复捕捉。实测约 5 秒，不合适在此微调。
CATCH_COOLDOWN = 5.0

# ── 球槽面板闭环检测（方案 C）──────────────────────────────────────

# 球槽面板模板文件名：点击捕捉按钮后，等待此模板出现才按球槽键。
# 截图要求：取面板的静态特征区块（边框/标题条），避开球图标和数量数字。
# 未放置时自动全程使用下方 CATCH_CLICK_DELAY 固定延时（开环模式）。
PANEL_TEMPLATE_NAME = "catchIng.png"

# 面板模板为"运行时分辨率原生截图"（如直接从 1920×1080 游戏画面裁取）：
# True = 匹配时不做 2560 基准缩放，原生尺寸直接使用（当前 catchIng.png 即此口径）。
# 若以后换成从 2560 宽参考分辨率截取的模板，改为 False。
PANEL_TEMPLATE_NATIVE = True

# 球槽面板搜索区域（屏幕左下 1/4，即四象限的左下象限）：
# (left, top, width, height) 相对窗口客户区的比例。
# 若面板特征区块不在此区域，检测恒为噪声分（超时日志的"最高分"~0.2x），
# 可按实际面板位置调整；区域越大匹配耗时越长（960×540 下仍远快于轮询间隔）。
PANEL_ROI = (0.0, 0.5, 0.5, 0.5)

# 面板出现判定阈值：匹配分 ≥ 此值认为面板已出现（好模板实测应 0.6+）
PANEL_DETECT_THRESHOLD = 0.5

# 等待面板出现的超时（秒）：超时后重试捕捉
PANEL_WAIT_TIMEOUT = 2.0
# 等待期间轮询间隔（秒）
PANEL_POLL_INTERVAL = 0.1
# 检测到面板后的保险延时（秒）：面板渲染完成 ≠ 立即可交互（弹出/淡入动画
# 期间按键会被吞），需盖住动画尾段+输入就绪窗口。若仍偶发选球失败，继续加大。
PANEL_SETTLE_DELAY = 0.35
# 连续 N 次等不到面板 → 本场战斗禁用闭环，降级为固定延时（下场自动恢复）
PANEL_MISS_LIMIT = 3

# 捕捉按钮连续 N 次定位失败 → 触发卡死恢复（球槽面板还开着则补发选球，
# 否则转逃跑兜底脱离战斗），防止卡在"按钮消失+界面无变化"的死循环
LOCATE_FAIL_LIMIT = 3

# ── 识别参数 ────────────────────────────────────────────────────────

# 虚脱判定下限：capture 匹配分的绝对下限，仅防止两者都低时的误判。
# 实测虚脱后 capture 分数仅 ~0.36（模板与实际按钮样式有差异），故取 0.30。
CATCH_DETECT_THRESHOLD = 0.3

# 虚脱判定主判据：capture 与 pollute 的分数差。
# 污染中 pollute 领先 0.15+，虚脱后 capture 领先 ~0.11，
# 反超差值 ≥ 此值才判定可捕捉（与模板绝对分数无关，更稳健）。
CATCH_REVERSE_MARGIN = 0.08

# 虚脱专用模板文件名：从虚脱状态（污染褪色后）的实际按钮截图制作，
# 放入 templates/ 目录后自动生效（约 84×84，与 capture.png 同规格）。
# 未放置时自动降级为只用 capture.png（当前行为）。
EXHAUSTED_TEMPLATE_NAME = "capture_exhausted.png"

# 防抖轮数：连续 N 轮满足上述条件后，再用延迟判型复判确认才转入捕捉。
# 设为 1 时由复判（延迟重截图）承担第二重确认，虚脱到捕捉约 1.5 秒；
# 若实战出现特效误触发复判，调回 2。
DEBOUNCE_ROUNDS = 1
